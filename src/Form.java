    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if (txtnombre.getText().trim().isEmpty()
        || txtdocumento.getText().trim().isEmpty()
        || txtfechaingreso.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.");
        return;
        }
        
        try {
        Empleados empleado = new Empleados();
        empleado.setNombre(txtnombre.getText().trim());
        empleado.setDocumento(txtdocumento.getText().trim());
        empleado.setCargo(cmbcargo.getSelectedItem().toString());
        empleado.setArea(cmbarea.getSelectedItem().toString().trim());
        empleado.setSalario(Double.parseDouble(spnsalario.getValue().toString()));
        empleado.setFechaIngreso(txtfechaingreso.getText().trim());
        listaEmpleados.add(empleado);
            RefrescarTabla();
        limpiarFormulario();
    }
    catch (Exception e){
        JOptionPane.showMessageDialog(this, "Error al agregar alumno");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

