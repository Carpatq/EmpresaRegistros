    @SuppressWarnings("unchecked")
    public void RefrescarTabla(){
        while (modelo.getRowCount() > 0){
        modelo.removeRow(0);
    }
        
        


    for (Empleados empleados : listaEmpleados) {
       Object a[] = new Object[6];
            a[0] = empleados.getNombre();
            a[1] = empleados.getDocumento();
            a[2] = empleados.getCargo();
            a[3] = empleados.getArea();
            a[4] = empleados.getSalario();
            a[5] = empleados.getFechaIngreso(); 
            modelo.addRow(a);
        }
    
    tbRegistro.setModel(modelo);
    }
    
